import { fileURLToPath } from 'node:url';
import { checkData, INDEX, readGeneratedFiles } from '../check-data.js';
import { refreshFixtures } from '../fixtures.js';
import { type ScrapeOptions, scrape } from '../scrape.js';
import { type Command, flag, list, text, UsageError } from './command.js';

/** Writing and checking the dataset, and the fixtures its parser is tested against. */

export const scrapeCommand: Command = {
  summary: 'scrape the MFM into data/: index, faction pages, validated YAML',
  help: `usage: mfm scrape [options]

Scrapes the Munitorum Field Manual into --out: each faction's YAML, validated, and on
a full run meta.yaml. Legends units and the rules panels need a browser (Playwright);
--no-legends skips it. A faction that fails doesn't stop the others, but the run exits
1 at the end. \`pnpm scrape\` runs this.

  --faction <slug>     one faction only; meta.yaml is left as it is
  --out <dir>          where the YAML goes (default: data)
  --concurrency <n>    faction pages in flight at once (default: 4)
  --no-legends         HTTP only: no browser, so no Legends and no rules panels
  --order <name|page>  entity order: name (default, alphabetical) or page
  --report <file>      write the per-faction failure report there, for
                       \`mfm report-failure\`
  --dates-from <dir>   another snapshot to match firstSeen against (repeatable)
`,
  options: {
    faction: { type: 'string' },
    out: { type: 'string' },
    concurrency: { type: 'string' },
    'no-legends': { type: 'boolean' },
    order: { type: 'string' },
    report: { type: 'string' },
    'dates-from': { type: 'string', multiple: true },
  },
  positionals: 0,
  async run(values) {
    const order = text(values, 'order') ?? 'name';
    if (order !== 'name' && order !== 'page') {
      throw new UsageError(`--order must be "name" or "page", got: ${order}`);
    }
    const concurrency = text(values, 'concurrency') ?? '4';
    if (!/^[1-9][0-9]*$/.test(concurrency)) {
      throw new UsageError(`--concurrency must be a whole number above 0, got: ${concurrency}`);
    }
    const opts: ScrapeOptions = {
      out: text(values, 'out') ?? 'data',
      concurrency: Number(concurrency),
      legends: !flag(values, 'no-legends'),
      order,
      datesFrom: list(values, 'dates-from'),
    };
    const faction = text(values, 'faction');
    if (faction) opts.faction = faction;
    const report = text(values, 'report');
    if (report) opts.report = report;
    return scrape(opts);
  },
};

export const refreshFixturesCommand: Command = {
  summary: 're-download the parser test fixtures from the live site',
  help: `usage: mfm refresh-fixtures [--only <name>]...

Re-downloads the HTML fixtures the parser tests run against into test/fixtures/
(\`pnpm refresh-fixtures\` runs this); then review the diff and update the snapshots
with \`pnpm test -u\`. Needs the network, and a browser for the two rendered fixtures.

  --only <name>  just this fixture (repeatable), leaving the rest as they are. An
                 unknown name stops the run before anything is downloaded.
`,
  options: { only: { type: 'string', multiple: true } },
  positionals: 0,
  async run(values) {
    await refreshFixtures(list(values, 'only'));
    return 0;
  },
};

/** The repository these commands ship in. */
const REPO_ROOT = fileURLToPath(new URL('../..', import.meta.url));

export const checkDataCommand: Command = {
  summary: 'check that the committed generated files are what the tools write',
  help: `usage: mfm check-data [--root <dir>]

Checks that the committed generated files are exactly what the tools would write (see
"Integrity of the committed files" in specs/data-model.md): every data/<slug>.yaml
passes the Faction schema, is named after its slug and is canonical; data/meta.yaml
passes SiteMeta and is canonical; and ${INDEX} is the index generated from
changelog/. Lists every problem and exits 1 when any file isn't.

  --root <dir>  the repository to check (default: the one this command is in)
`,
  options: { root: { type: 'string' } },
  positionals: 0,
  async run(values, _, io) {
    const files = readGeneratedFiles(text(values, 'root') ?? REPO_ROOT);
    const problems = checkData(files);
    if (problems.length === 0) {
      const factions = files.data.filter((f) => f.name !== 'meta.yaml').length;
      io.out(`check-data: ${factions} faction files, meta.yaml and ${INDEX} are canonical.\n`);
      return 0;
    }
    for (const p of problems) io.err(`✗ ${p}\n\n`);
    io.err(
      `check-data: ${problems.length} problem${problems.length === 1 ? '' : 's'}. These files are ` +
        'generated by the scraper; see "Integrity of the committed files" in specs/data-model.md.\n',
    );
    return 1;
  },
};
